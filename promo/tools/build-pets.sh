#!/usr/bin/env bash
# Slice every <name>-3x3.png sprite sheet into the 9 canonical Waddly frames.
#
# Canonical order (row-major): idle-1, idle-2, typing-1, typing-2, typing-3,
# typing-4, enter-1, sleep-1, sleep-2  — see README.md §画像を用意する.
#
#   promo/assets/pets/<name>-3x3.png  ->  promo/assets/frames/<name>/<frame>.png
#
# Drop new sheets into assets/pets/ and re-run; nothing else needs editing.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/assets/pets"
OUT="$ROOT/assets/frames"
SCALE="${SCALE:-1}"

FRAMES=(idle-1 idle-2 typing-1 typing-2 typing-3 typing-4 enter-1 sleep-1 sleep-2)

shopt -s nullglob
sheets=("$SRC"/*-3x3.png)
if [ ${#sheets[@]} -eq 0 ]; then
  echo "no sprite sheets found in $SRC" >&2
  exit 1
fi

for sheet in "${sheets[@]}"; do
  base="$(basename "$sheet")"
  name="${base%-3x3.png}"
  w=$(magick identify -format '%w' "$sheet")
  h=$(magick identify -format '%h' "$sheet")
  if [ "$w" -ne "$h" ] || [ $((w % 3)) -ne 0 ]; then
    echo "skip $base: must be square with a side divisible by 3 (got ${w}x${h})" >&2
    continue
  fi
  cell=$((w / 3))
  dest="$OUT/$name"
  rm -rf "$dest"
  mkdir -p "$dest"
  for i in "${!FRAMES[@]}"; do
    row=$((i / 3))
    col=$((i % 3))
    magick "$sheet" -crop "${cell}x${cell}+$((col * cell))+$((row * cell))" +repage \
      -filter point -resize "$((cell * SCALE))x$((cell * SCALE))" \
      -strip "$dest/${FRAMES[$i]}.png"
  done
  echo "sliced $base -> assets/frames/$name (${cell}px cells, ${SCALE}x, nearest-neighbour)"
done

# Generated sheets sometimes bleed a few pixels across a grid line; those show up
# as a speck floating beside the pet. Strip them when a Pillow-enabled Python is
# available (override with PYTHON=/path/to/python3).
# Publish the list of available characters for the composition to read.
{
  echo "/* Generated by tools/build-pets.sh — the characters available to the promo. */"
  echo "window.PET_SETS = ["
  for dir in "$OUT"/*/; do
    name="$(basename "$dir")"
    count=$(ls "$dir"*.png 2>/dev/null | wc -l | tr -d ' ')
    [ "$count" -eq 9 ] || continue
    echo "    { id: \"$name\", base: \"assets/frames/$name\" },"
  done
  echo "];"
} > "$ROOT/scripts/pets.js"
echo "wrote scripts/pets.js"

PYTHON="${PYTHON:-python3}"
if "$PYTHON" -c 'import PIL' >/dev/null 2>&1; then
  for dir in "$OUT"/*/; do
    "$PYTHON" "$ROOT/tools/despeckle.py" "$dir"*.png
  done
else
  echo "note: $PYTHON has no Pillow — skipped despeckle" >&2
fi
